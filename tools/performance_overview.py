"""Rebuild the performance overview from portable timing CSVs.

Use --extract PATH to refresh September cell medians from measurements.parquet.
Requires pandas and matplotlib; parquet extraction also requires pyarrow.
"""
from pathlib import Path
import argparse
import hashlib
import json
import math
import pandas as pd
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'docs/benchmarks/overview'
NAMES = {'sklearn_random_forest': 'scikit-learn RF', 'catboost_symmetric': 'CatBoost symmetric',
         'xgboost_depthwise': 'XGBoost depthwise', 'xgboost_lossguide': 'XGBoost lossguide',
         'lightgbm_leafwise': 'LightGBM leafwise'}


def extract(path):
    df = pd.read_parquet(path)
    assert len(df) == 52275
    df['latency_us'] = df.elapsed_ns / df.loops / 1000
    keys = ['cell_id', 'model_id', 'engine', 'device', 'batch_rows', 'cpu_threads',
            'nvforest_chunk', 'family', 'tree_count', 'max_depth', 'features',
            'model_dtype', 'model_sha256', 'input_sha256']
    proc = df.groupby(keys + ['repetition'], dropna=False).latency_us.median()
    cells = proc.groupby(level=list(range(len(keys))), dropna=False).agg(['median', 'min', 'max', 'count']).reset_index()
    assert (cells['count'] == 5).all()
    cells.to_csv(OUT / 'release-cells.csv', index=False)
    (OUT / 'release-source.json').write_text(json.dumps({
        'source': path.name, 'sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
        'run_id': df.run_id.iloc[0], 'intervals': len(df), 'method': 'Median of three intervals per process, then median of five processes. min/max are process medians.',
        'revision': '856f875 + collector 47da87d', 'date': '2026-09-26'}, indent=2) + '\n')


def ratios(cells, engine, device, threads, best=False):
    subset = cells[cells.device.eq(device)]
    if device == 'cpu':
        subset = subset[subset.cpu_threads.eq(threads)]
    keys = ['model_id', 'batch_rows', 'family', 'model_sha256', 'input_sha256', 'model_dtype']
    p = subset[subset.engine.eq('pyre')][keys + ['median']]
    c = subset[subset.engine.eq(engine)]
    if engine == 'nvforest' and not best:
        c = c[c.nvforest_chunk.isna()]
    c = c.groupby(keys, dropna=False)['median'].min().reset_index()
    pair = p.merge(c, on=keys, suffixes=('_pyre', '_other'), validate='one_to_one')
    pair['ratio'] = pair.median_other / pair.median_pyre
    return pair


def geo(values):
    return math.exp(sum(math.log(x) for x in values) / len(values))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--extract', type=Path)
    args = parser.parse_args()
    if not args.extract and not (OUT / 'release-cells.csv').exists():
        parser.error('pass --extract PATH to the historical measurements.parquet on the first run')
    if args.extract:
        extract(args.extract.resolve())
    cells = pd.read_csv(OUT / 'release-cells.csv')
    rows = []
    for threads in [1, 8]:
        pair = ratios(cells, 'native', 'cpu', threads)
        for family, group in pair.groupby('family'):
            rows.append({'family': family, 'threads': threads, 'all_batches': geo(group.ratio),
                         'rows_65536': geo(group[group.batch_rows.eq(65536)].ratio), 'pairs': len(group)})
    native = pd.DataFrame(rows)
    native.to_csv(OUT / 'native-speedups.csv', index=False)
    gpu = pd.read_csv(OUT / 'gpu-screen.csv')
    gpu['default_mrows_s'] = gpu.rows / gpu.pyre_default_us
    gpu['tuned_mrows_s'] = gpu.rows / gpu.pyre_tuned_us
    gpu['speedup_best'] = gpu.nvforest_best_us / gpu.pyre_tuned_us
    gpu.to_csv(OUT / 'gpu-derived.csv', index=False)
    lines = ['# Performance comparison and capacity estimates', '',
             'Generated by `tools/performance_overview.py`. Ratios are competitor latency / Pyre latency; above 1 favors Pyre.', '',
             '## Historical matched CPU framework comparisons', '',
             'September 26, 2026, runtime `856f875`; these numbers predate packed CPU traversal and parallel symmetric execution. Each ratio compares the same trained model, input bytes, precision, batch and requested thread count. All-batch geometric means weight batches 1/32/256/4096/65536 equally. They are not large-batch capacity estimates.', '',
             '| Native predictor / tree family | Threads | All batches | 65,536 rows | Matched cells |',
             '| --- | ---: | ---: | ---: | ---: |']
    for row in native.itertuples():
        lines.append(f'| {NAMES[row.family]} | {row.threads} | {row.all_batches:.2f}× | {row.rows_65536:.2f}× | {row.pairs} |')
    lines += ['', '## Historical matched nvForest comparisons', '', '| Path | Default chunk | Best measured chunk | Cells |', '| --- | ---: | ---: | ---: |']
    for device, threads in [('cpu', 1), ('cpu', 8), ('gpu', None)]:
        default = ratios(cells, 'nvforest', device, threads)
        best = ratios(cells, 'nvforest', device, threads, True)
        lines.append(f'| {device.upper()}' + (f', {threads} threads' if threads else '') + f' | {geo(default.ratio):.2f}× | {geo(best.ratio):.2f}× | {len(default)} |')
    lines += ['', '## Historical CPU capacity anchors', '',
              '65,536 resident rows, 32 features, eight requested threads. M rows/s are derived from measured median latency. The last column is an illustrative 2× extrapolation to 16 physical cores for general traversal only; it is not a current-runtime forecast. The historical compact CatBoost path was serial, so that extrapolation does not apply.', '',
              '| Family | Trees / actual depth | Precision | Observed M rows/s | Ideal 16-core M rows/s |',
              '| --- | ---: | --- | ---: | ---: |']
    capacity = cells[cells.engine.eq('pyre') & cells.device.eq('cpu') & cells.cpu_threads.eq(8) & cells.batch_rows.eq(65536)]
    capacity = capacity[((capacity.tree_count == 16) & (capacity.max_depth == 4)) | ((capacity.tree_count.isin([64, 256])) & (capacity.max_depth == 8))]
    capacity = capacity.sort_values(['family', 'tree_count'])
    for r in capacity.itertuples():
        rate = r.batch_rows / r.median
        ideal = 'Not applicable: serial' if r.family == 'catboost_symmetric' else f'{2*rate:.2f}'
        lines.append(f'| {NAMES[r.family]} | {r.tree_count} / {r.max_depth} | {r.model_dtype} | {rate:.2f} | {ideal} |')
    lines += ['', '## Latest saved GPU screen', '',
              'November 9, 2026 algorithm snapshot, before the Mojo 1.2 toolchain port. RTX 5090, resident input, reused output, completed native calls. One process, median of three intervals of at least 20 ms; desktop drift reached about 10%. Tuning cost is excluded. Close differences are inconclusive. Values transcribed from [GPU kernel evidence](../gpu-kernel.md).', '',
              '| Configuration | Rows | Pyre default µs | Pyre tuned µs | nvForest auto µs | nvForest best µs | Tuned speedup vs best | Default / tuned M rows/s |',
              '| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |']
    for r in gpu.itertuples():
        lines.append(f'| {r.configuration} | {r.rows:,} | {r.pyre_default_us:g} | {r.pyre_tuned_us:g} | {r.nvforest_auto_us:g} | {r.nvforest_best_us:g} | {r.speedup_best:.2f}× | {r.default_mrows_s:,.0f} / {r.tuned_mrows_s:,.0f} |')
    (OUT / 'README.md').write_text('\n'.join(lines) + '\n\n' + (OUT / 'methodology.md').read_text())
    plt.rcParams.update({'font.size': 10, 'axes.spines.top': False, 'axes.spines.right': False,
                         'svg.hashsalt': 'pyre-performance'})
    fig, axes = plt.subplots(1, 3, figsize=(16, 5.8), gridspec_kw={'width_ratios': [1.2, 1, 1]})
    ax = axes[0]
    labels = list(NAMES)
    for offset, threads, color in [(-.18, 1, '#007b83'), (.18, 8, '#e98732')]:
        data = native[native.threads.eq(threads)].set_index('family').loc[labels]
        bars = ax.barh([i + offset for i in range(5)], data.rows_65536, height=.34, color=color, label=f'{threads} thread(s)')
        ax.bar_label(bars, fmt='%.2f×', padding=4, fontsize=9)
    ax.set_yticks(range(5), [NAMES[k] for k in labels])
    ax.invert_yaxis(); ax.axvline(1, color='#666', linestyle='--', linewidth=1)
    ax.set_xlim(0, native.rows_65536.max()*1.3)
    ax.set_xlabel('Native predictor time / Pyre time')
    ax.set_title('CPU framework comparison\nHistorical · Sep 26 · 65,536 rows', fontsize=12)
    ax.legend(loc='lower right', frameon=False)
    data = gpu.iloc[:8].iloc[::-1]
    for ax, field, title, unit, color in [
        (axes[1], 'speedup_best', 'GPU vs nvForest best setting\nExploratory · Nov 9 · tuned Pyre', 'nvForest time / Pyre time', '#007b83'),
        (axes[2], 'tuned_mrows_s', 'GPU resident throughput\nSame screen · 65,536 rows', 'Million rows/s · log scale', '#4c65a8')]:
        bars = ax.barh(data.configuration, data[field], color=color)
        ax.bar_label(bars, labels=[f'{x:.2f}×' if field == 'speedup_best' else f'{x:,.0f}' for x in data[field]], padding=4, fontsize=9)
        ax.set_title(title, fontsize=12); ax.set_xlabel(unit)
        if field == 'speedup_best':
            ax.axvline(1, color='#666', linestyle='--', linewidth=1); ax.set_xlim(0, data[field].max()*1.25)
        else:
            ax.set_xscale('log'); ax.set_xlim(100, 18000)
    fig.suptitle('Pyre on Ryzen 9 5950X + RTX 5090', fontsize=17, weight='bold')
    fig.text(.5, .025, 'Matched models within each comparison. Different dates and call scopes across panels. Resident throughput excludes transfers; saturation is unproven.', ha='center', fontsize=10)
    fig.tight_layout(rect=[0, .065, 1, .94], w_pad=2)
    fig.savefig(OUT / 'performance.svg', metadata={'Date': None})
    fig.savefig(OUT / 'performance.png', dpi=180)
    plt.close(fig)

if __name__ == '__main__':
    main()
